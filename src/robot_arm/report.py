"""Markdown/HTML summary reports for ``robot-arm-workcell-sim``.

Both builders take the result dictionary produced by
:func:`robot_arm.simulate.run_scenario` (metrics + phase table + file
list) and render a human-readable summary.  The HTML report is a single
self-contained file with inline CSS; it links to the PNG plots next to it.
"""

from __future__ import annotations

import html


def _metrics_rows(result):
    """Return ``(label, value)`` rows for the headline metric table."""
    clearance = result.get("min_clearance_m")
    return [
        ("Scenario", result.get("scenario", "")),
        ("Workcell", result.get("cell", "")),
        ("Success", "YES" if result.get("success") else "NO"),
        ("Cycle time", f"{result.get('cycle_time_s', 0.0):.2f} s"),
        ("Total joint travel", f"{result.get('total_joint_travel_rad', 0.0):.3f} rad"),
        ("Max joint speed", f"{result.get('max_joint_speed_rad_s', 0.0):.3f} rad/s"),
        (
            "Min collision clearance",
            f"{clearance:.4f} m" if clearance is not None else "n/a (no obstacles)",
        ),
        ("Samples", str(result.get("n_samples", 0))),
        (
            "Pick",
            ", ".join(f"{v:.3f}" for v in result.get("pick_m", [])) + " m"
            if result.get("pick_m")
            else "—",
        ),
        (
            "Place",
            ", ".join(f"{v:.3f}" for v in result.get("place_m", [])) + " m"
            if result.get("place_m")
            else "—",
        ),
    ]


def build_markdown_report(result, out_path):
    """Write the Markdown summary report for ``result`` to ``out_path``."""
    lines = [
        f"# Simulation report — {result.get('scenario', '')}",
        "",
    ]
    if result.get("description"):
        lines += [result["description"], ""]
    lines += ["## Metrics", ""]
    lines += ["| Metric | Value |", "| --- | --- |"]
    for label, value in _metrics_rows(result):
        lines.append(f"| {label} | {value} |")
    lines += ["", "## Phases", ""]
    lines += [
        "| Phase | Duration [s] | Gripper | Cartesian | Travel [rad] | "
        "Max speed [rad/s] | Min clearance [m] |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for ph in result.get("phases", []):
        clearance = ph.get("min_clearance_m")
        lines.append(
            f"| {ph.get('label', '')} | {ph.get('duration_s', 0.0):.3f} | "
            f"{ph.get('gripper', '')} | "
            f"{'yes' if ph.get('cartesian') else 'no'} | "
            f"{ph.get('joint_travel_rad', 0.0):.3f} | "
            f"{ph.get('max_joint_speed_rad_s', 0.0):.3f} | "
            f"{clearance if clearance is not None else 'n/a'} |"
        )
    notes = result.get("notes") or []
    if notes:
        lines += ["", "## Notes", ""]
        lines += [f"- {note}" for note in notes]
    files = result.get("files") or {}
    if files:
        lines += ["", "## Output files", ""]
        lines += [f"- `{name}`" for name in files.values()]
    lines += [
        "",
        "Generated by `robot-arm-workcell-sim` "
        "(`robot-arm simulate --scenario <file> --out <dir>`).",
        "",
    ]
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    return out_path


def build_html_report(result, out_path):
    """Write the standalone HTML summary report for ``result``."""
    rows = "".join(
        f"<tr><th>{html.escape(label)}</th><td>{html.escape(value)}</td></tr>"
        for label, value in _metrics_rows(result)
    )
    phase_rows = ""
    for ph in result.get("phases", []):
        clearance = ph.get("min_clearance_m")
        phase_rows += (
            "<tr>"
            f"<td>{html.escape(str(ph.get('label', '')))}</td>"
            f"<td>{ph.get('duration_s', 0.0):.3f}</td>"
            f"<td>{html.escape(str(ph.get('gripper', '')))}</td>"
            f"<td>{'yes' if ph.get('cartesian') else 'no'}</td>"
            f"<td>{ph.get('joint_travel_rad', 0.0):.3f}</td>"
            f"<td>{ph.get('max_joint_speed_rad_s', 0.0):.3f}</td>"
            f"<td>{clearance if clearance is not None else 'n/a'}</td>"
            "</tr>"
        )
    notes = "".join(
        f"<li>{html.escape(note)}</li>" for note in (result.get("notes") or [])
    )
    notes_html = f"<h2>Notes</h2><ul>{notes}</ul>" if notes else ""
    files = result.get("files") or {}
    figures = ""
    if files.get("trajectory_png"):
        figures += (
            '<h2>Trajectory</h2><img src="trajectory.png" '
            'alt="trajectory plot" style="max-width:100%">'
        )
    if files.get("joints_png"):
        figures += (
            '<h2>Joint trajectories</h2><img src="joints.png" '
            'alt="joint trajectory plot" style="max-width:100%">'
        )
    doc = f"""<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8">
<title>Simulation report — {html.escape(str(result.get('scenario', '')))}</title>
<style>
body {{ font-family: sans-serif; max-width: 900px; margin: 2em auto; padding: 0 1em; color: #1d2a32; }}
table {{ border-collapse: collapse; width: 100%; }}
th, td {{ border: 1px solid #ccc; padding: 6px 10px; text-align: left; }}
th {{ background: #f0f0f0; }}
h1 {{ font-size: 1.5em; }} h2 {{ font-size: 1.2em; margin-top: 1.5em; }}
</style></head>
<body>
<h1>Simulation report — {html.escape(str(result.get('scenario', '')))}</h1>
<p>{html.escape(str(result.get('description', '')))}</p>
<h2>Metrics</h2>
<table>{rows}</table>
<h2>Phases</h2>
<table><tr><th>Phase</th><th>Duration [s]</th><th>Gripper</th><th>Cartesian</th>
<th>Travel [rad]</th><th>Max speed [rad/s]</th><th>Min clearance [m]</th></tr>
{phase_rows}</table>
{notes_html}
{figures}
<p><small>Generated by robot-arm-workcell-sim.</small></p>
</body></html>
"""
    with open(out_path, "w") as fh:
        fh.write(doc)
    return out_path
